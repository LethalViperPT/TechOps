"""
Operações aritméticas em Python
"""

valor_x = 8
valor_y = 6

# Soma

soma = valor_x + valor_y
print(f"A soma de {valor_x} e {valor_y} é igual a {soma}.")

# Subtração

subtracao = valor_y - valor_x
print(f"A subtração de {valor_x} e {valor_y} é igual a {subtracao}.")

# Multiplicação

multiplicacao = valor_x * valor_y
print(f"A multiplicação de {valor_x} e {valor_y} é igual a {multiplicacao}")

# Divisão

divisao = valor_x / valor_y
print(f"A divisão de {valor_x} e {valor_y} é igual a {divisao}")

